#!/usr/bin/env python3
"""Emits pipe_step.h: a phased gfx11 Low step that issues the next K16 slice's LDS fragment reads, then the current
slice's WMMAs (NF row fragments x NC column fragments). Usage: gen.py NF NC A_STRIDE B_STRIDE > pipe_step.h"""
import sys

nf, nc, sa, sb = (int(v) for v in sys.argv[1:5])
mode = sys.argv[5] if len(sys.argv) > 5 else "bulk"
V8 = "reg<amdgpu.vgpr x8>"
c = [f"%c{i}_{j}" for i in range(nf) for j in range(nc)]
a = [f"%a{i}" for i in range(nf)]
b = [f"%b{j}" for j in range(nc)]
R = "reg<amdgpu.vgpr>"
formals = [f"{x}: {V8}" for x in c + a + b] + [f"%xr: {R}", f"%xo: {R}", f"%wr: {R}", f"%wo: {R}"]
body = ["  low.schedule.begin", "  %xa = v_add_u32 %xr, %xo", "  %wa = v_add_u32 %wr, %wo"]
def reads(name, base, stride, i):
    o = i * stride
    return [f"  %{name}{i}l = ds_read_b128 {base} {{offset = {o}}}",
            f"  %{name}{i}h = ds_read_b128 {base} {{offset = {o + 16}}}",
            f"  %{name}{i} = concat(%{name}{i}l, %{name}{i}h) : (reg<amdgpu.vgpr x4>, reg<amdgpu.vgpr x4>) -> {V8}"]
mmas = [f"  %d{i}_{j} = v_wmma_f32_16x16x16_bf16 %a{i}, %b{j}, %c{i}_{j}" for i in range(nf) for j in range(nc)]
loads = [reads("nb", "%wa", sb, j) for j in range(nc)] + [reads("na", "%xa", sa, i) for i in range(nf)]
if mode == "bulk":
    for l in loads:
        body += l
    body.append("  low.schedule.phase")
    body += mmas
else:
    per = -(-len(mmas) // len(loads))
    for k, l in enumerate(loads):
        body += l
        body.append("  low.schedule.phase")
        body += mmas[k * per:(k + 1) * per]
        body.append("  low.schedule.phase")
    body += mmas[len(loads) * per:]
body.append("  low.schedule.end")
rets = [f"%d{i}_{j}" for i in range(nf) for j in range(nc)] + [f"%na{i}" for i in range(nf)] + [f"%nb{j}" for j in range(nc)]
body.append("  return " + ", ".join(rets))
sig = "(" + ", ".join(formals) + ") -> (" + ", ".join([V8] * len(rets)) + ") {"
tag = f"{nf}x{nc}"
accs = ", ".join(f"c{i}_{j}" for i in range(nf) for j in range(nc))
fa = ", ".join(f"a{i}" for i in range(nf))
fb = ", ".join(f"b{j}" for j in range(nc))
args = ", ".join([f"s.c{i}_{j}" for i in range(nf) for j in range(nc)] + [f"s.a{i}" for i in range(nf)] + [f"s.b{j}" for j in range(nc)])
print(f"""// SPDX-License-Identifier: MIT
// Generated by gen.py {nf} {nc} {sa} {sb}: one software-pipelined K16 step of a {nf} x {nc} WMMA fragment block.
#ifndef WP_PIPE_STEP_{tag}_H_
#define WP_PIPE_STEP_{tag}_H_
#include <loomcxx/low.h>
namespace wp {{
struct [[loom::representation("amdgpu.gfx11.generic.core")]] Gfx11 {{}};
typedef __bf16 bf16x16 __attribute__((ext_vector_type(16)));
typedef float f32x8 __attribute__((ext_vector_type(8)));
struct Step{tag} {{
  f32x8 {accs};
  bf16x16 {fa}, {fb};
}};
// Reads the next slice's fragments (A at xa + i {sa} bytes, B at wa + j {sb}), then multiplies the current ones.
LOOM_INLINE Step{tag} pipe_step(Step{tag} s, const __bf16* xa, const __bf16* wa) {{
  return loom::low::assembly<Gfx11, Step{tag}>(R"({sig}
""" + "\n".join(body) + f"""
}})", {args}, xa, wa);
}}
}}  // namespace wp
#endif""")
